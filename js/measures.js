// 저감방안 — 종의 위협 요인(분류군 기본 + 종별)과 민감 시기, 사업지 영향 정도에 맞춰 회피·최소화·보상·관리 방안을 고름
// 환경영향평가에서 흔히 쓰는 일반 방안을 요약한 것으로, 실제 적용은 현지조사와 관계 기관 협의로 정함
window.Measures = (() => {
  const STAGE = { avoid: ["회피", "s-avoid"], min: ["최소화", "s-min"], comp: ["보상", "s-comp"], mon: ["관리", "s-mon"] };
  const ORDER = ["avoid", "min", "comp", "mon"];
  const ha = (v) => `${Number(v).toLocaleString("ko-KR", { maximumFractionDigits: 1 })} ha`;

  // ‘번식 4–7’, ‘이동 4–5·8–10’, ‘포자 연중’ → { kind, text: ‘번식기(4~7월)’ }
  const season = (s) => {
    const m = /^(\S+)\s+(.+)$/.exec(s || "");
    if (!m) return null;
    const when = m[2] === "연중" ? "연중" : m[2].split("·").map((p) => `${p.replace("–", "~")}월`).join(", ");
    const name = { 번식: "번식기", 산란: "산란기", 개화: "개화기", 월동: "월동기", 이동: "이동 시기", 동면: "동면기", 회유: "회유 시기", 성충: "성충 활동기", 활동: "활동기", 포자: "포자 형성기", 성숙: "성숙기" }[m[1]] || m[1];
    return { kind: m[1], when, text: when === "연중" ? `연중 ${m[1]}` : `${name}(${when})` };
  };

  const BY_STRESS = {
    훼손: (c) => [
      ["avoid", c && c.lostHa > 0 ? `사업 구역 안의 적합 서식지(약 ${ha(c.lostHa)})를 구역에서 빼거나 시설 배치를 바꿔 훼손을 피합니다.`
        : "적합 서식지(지도의 ‘적합’ 이상)에는 시설을 두지 않도록 배치합니다."],
      ["comp", c && c.lostHa > 0 ? `피할 수 없는 훼손 면적 이상(약 ${ha(c.lostHa)} 이상)을 가까운 대체서식지에 조성·복원합니다.`
        : "피할 수 없는 훼손이 생기면 그 면적 이상을 가까운 대체서식지에 조성·복원합니다."],
    ],
    소음: () => [["min", "저소음·저진동 공법과 장비를 쓰고 서식지 쪽에 가설 방음벽을 세웁니다. 발파·항타는 시간을 정해 짧게 합니다."]],
    수질: () => [["min", "가배수로·침사지·오탁방지막으로 흙탕물이 물길에 들지 않게 하고, 물속 공사는 갈수기에 짧게 합니다."]],
    조명: () => [["min", "야간 공사를 줄이고, 조명은 아래로 비추는 차광형·장파장(주황빛) 등으로 서식지 쪽 빛을 막습니다."]],
    로드킬: () => [["min", "도로·공사 진입로를 따라 유도 울타리와 생태통로(암거형·박스형)를 두고, 공사 차량은 서행합니다."]],
    단절: (c, sp) => [["min", sp.group === "fish"
      ? "보·낙차공 등 하천을 가로지르는 시설에는 어도를 두고 하천 바닥이 끊기지 않게 해 물고기가 오르내리게 합니다."
      : "서식지가 끊기지 않도록 생태통로·녹지 띠를 두고, 물길을 건너는 구조물은 동물이 지날 수 있는 높이·폭으로 만듭니다."]],
    채집: () => [["min", "서식 위치는 공개하지 않고, 공사 관계자 교육과 출입 통제로 불법 채집·포획을 막습니다."]],
    교란: () => [["min", "번식지·잠자리·먹이터 주변에 완충 구역을 두고 그 안에는 사람과 장비 출입을 줄입니다."]],
    수위: () => [["min", "물 돌리기·지하수 뽑기를 줄여 습지·하천의 수위와 물 흐름이 바뀌지 않게 하고, 공사 뒤 원래 수위를 되살립니다."]],
    벌채: () => [["avoid", "큰 나무·고사목·구멍이 있는 나무는 남기고, 벌채는 번식기를 피해 합니다."]],
  };

  const BY_GROUP = {
    plant: [["comp", "공사 전 개체를 모두 조사해 생육 조건이 같은 가까운 곳으로 이식하고, 종자·표토를 확보해 증식합니다. 이식지는 3년 이상 활착을 확인합니다."]],
    fungi: [["comp", "자실체가 나는 고목·토양을 함께 옮기거나, 서식 숲을 보전 구역으로 남깁니다."]],
    algae: [["avoid", "서식 암반·조간대를 매립·준설 구역에서 빼는 것을 먼저 검토합니다."]],
    herp: [["min", "공사 전에 전문가와 함께 개체를 포획해 서식 조건이 같은 가까운 곳으로 옮깁니다(이주)."]],
    fish: [["min", "물막이 전에 전문가와 함께 개체를 포획해 같은 수계의 영향 없는 구간으로 옮깁니다(이주)."]],
    insect: [["min", "공사 전에 애벌레·먹이식물을 함께 옮기고, 먹이식물·흡밀식물을 대체서식지에 심습니다."]],
    invert: [["min", "공사 전에 개체를 포획해 서식 조건이 같은 가까운 곳으로 옮깁니다(이주)."]],
    bird: [["avoid", "번식이 확인된 둥지 주변은 번식이 끝날 때까지 공사를 멈춥니다."]],
    mammal: [["min", "흔적(배설물·발자국·굴) 조사로 이동 경로를 확인해 생태통로 위치를 정합니다."]],
  };

  const bySeason = (sp) => {
    const s = season(sp.season);
    if (!s) return [];
    if (s.when === "연중") {
      return ["번식", "산란"].includes(s.kind) ? [["min", "연중 번식하므로 서식지 주변 공사는 구간을 나눠 짧게 하고, 소음이 큰 공종은 서식지에서 멀리 둡니다."]] : [];
    }
    if (["번식", "산란", "동면"].includes(s.kind)) {
      const what = s.kind === "동면" ? "동면 장소(굴·돌무더기·땅속) 주변 땅깎기·벌채" : "서식지 주변의 소음이 큰 공사(발파·항타·벌채)와 물속 공사";
      return [["min", `${s.text}에는 ${what}를 피하도록 공정을 조정합니다.`]];
    }
    if (["월동", "이동", "회유"].includes(s.kind)) return [["min", `${s.text}에는 도래지·휴식지 주변 공사와 사람 출입을 줄입니다.`]];
    if (["개화", "포자", "성숙"].includes(s.kind)) return [["min", `${s.text}에 개체 위치를 확인·표시해 두고, 이식은 생육이 멈춘 늦가을~이른 봄에 합니다.`]];
    if (["성충", "활동"].includes(s.kind)) return [["min", `${s.text}에는 서식지 주변 야간 조명과 먹이식물 훼손을 줄입니다.`]];
    return [];
  };

  // ctx(영향 예측 결과): { lostHa, grade } — 없으면 일반 방안
  const list = (sp, ctx) => {
    const out = [];
    const seen = new Set();
    const add = ([stage, text]) => { if (!seen.has(text)) { seen.add(text); out.push({ stage, text }); } };
    bySeason(sp).forEach(add);
    (sp.stress || []).forEach((k) => (BY_STRESS[k] ? BY_STRESS[k](ctx, sp) : []).forEach(add));
    (BY_GROUP[sp.group] || []).forEach(add);
    if (sp.grade) add(["mon", "멸종위기 야생생물을 포획·채취·이식하거나 훼손하려면 환경부(유역·지방환경청) 허가를 받아야 합니다(야생생물 보호 및 관리에 관한 법률 제14조)."]);
    if (sp.nm) add(["mon", "천연기념물은 포획·채취나 서식지 현상변경에 국가유산청 허가가 필요한지 확인합니다(자연유산의 보존 및 활용에 관한 법률)."]);
    add(["mon", "공사 전 정밀조사로 서식 여부를 확인하고, 공사 중과 준공 뒤(3년 이상) 모니터링으로 저감 효과를 확인합니다."]);
    return out.sort((a, b) => ORDER.indexOf(a.stage) - ORDER.indexOf(b.stage));
  };

  const html = (items, esc) => `<ul class="measures">${items.map((m) => `<li><span class="stage ${STAGE[m.stage][1]}">${STAGE[m.stage][0]}</span><span>${esc(m.text)}</span></li>`).join("")}</ul>`;
  const text = (items) => items.map((m) => `[${STAGE[m.stage][0]}] ${m.text}`).join("\n");

  return { list, html, text, season };
})();
